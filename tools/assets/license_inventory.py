def generated_set(root):
    """Files the texture and sound generators write."""
    out = {}
    tj = os.path.join(root, 'tools', 'texbuild', 'targets.json')
    if os.path.exists(tj):
        for p in json.load(open(tj)):
            out[p.lower()] = 'tools/texbuild'
    sb = os.path.join(root, 'tools', 'soundbuild', 'build_sounds.py')
    if os.path.exists(sb):
        for p in re.findall(r"\('(sound/[^']+)'", open(sb).read()):
            out[p.lower()] = 'tools/soundbuild'
    return out


# ---------------------------------------------------------------- units
def map_names(files):
    return sorted({os.path.basename(p)[:-4] for p in files if re.match(r'^maps/[^/]+\.bsp$', p)}, key=len, reverse=True)


def unit_of(p, maps):
    """(unit, area) for a normalised path."""
    pk3 = ''
    if '!' in p:
        pk3, p = p.split('!', 1)
    s = p.split('/')
    if s[0] == 'models' and len(s) > 2 and s[1] == 'players':
        if s[2] in ('heads', 'plates', 'wheels'):
            return f'Autoteile {s[2]}', 'Autos'
        if '.' in s[2]:
            return 'Autoteile allgemein', 'Autos'
        return f'Auto {s[2]}', 'Autos'
    if s[0] == 'sound' and len(s) > 2 and s[1] == 'player':
        return 'Sounds player (Hupen, Auto-Sounds)', 'Sounds'
    name = os.path.basename(p).lower()
    stem = re.sub(r'\.[a-z0-9]+$', '', name)
    for m in maps:
        if (s[0] in ('maps', 'levelshots') and (stem == m or stem.startswith(m + '_') or (len(s) > 2 and s[1] == m))) \
                or (s[0] == 'scripts' and stem == m) \
                or (s[0] == 'textures' and len(s) > 2 and s[1] == m):
            return f'Karte {m}', 'Karten'
    if s[0] == 'maps':
        return 'Karten-Zubehör (maps/)', 'Karten'
    if s[0] == 'levelshots':
        return 'Levelshots ohne Karte', 'Karten'
    if s[0] == 'env' or (s[0] == 'textures' and len(s) > 3 and s[1] == 'q3r_skies' and s[2] == 'env'):
        sky = s[3] if s[0] == 'textures' else (s[1] if len(s) > 2 else re.sub(r'_(bk|dn|ft|lf|rt|up)$', '', stem))
        return f'Skybox {sky}', 'Himmel'
    if s[0] == 'music':
        return f'Musik {name}', 'Musik'
    if s[0] == 'sound':
        return (f'Sounds {s[1]}/{s[2]}' if len(s) > 3 else f'Sounds {s[1]}' if len(s) > 2 else 'Sounds allgemein'), 'Sounds'
    if s[0] == 'textures' and len(s) > 2:
        return f'Texturen {s[1]}', 'Texturen'
    if s[0] == 'models' and len(s) > 3:
        return f'Modelle {s[1]}/{s[2]}', 'Modelle'
    if s[0] == 'models' and len(s) > 2:
        return f'Modelle {s[1]}', 'Modelle'
    if s[0] == 'fonts':
        return 'Schriften', 'Oberfläche'
    if s[0] in ('menu', 'gfx', 'icons', 'ui'):
        return (f'{s[0]}/{s[1]}' if len(s) > 2 else s[0]), 'Oberfläche'
    if s[0] in ('scripts', 'botfiles') or name.endswith(('.cfg', '.txt', '.menu', '.arena', '.game', '.shader', '.def', '.ent', '.skin')):
        return ('Bot-Dateien' if s[0] == 'botfiles' else 'Skripte, Shader, Konfiguration'), 'Text/Code'
    return (s[0] if len(s) > 1 else 'Sonstiges (Wurzel)'), 'Sonstiges'


# ---------------------------------------------------------------- main
def walk(base):
    out = []
    for dp, dn, fn in os.walk(base):
        for f in fn:
            full = os.path.join(dp, f)
            rel = os.path.relpath(full, base).replace('\\', '/')
            if rel.lower().endswith('.pk3'):
                with zipfile.ZipFile(full) as z:
                    for i in z.infolist():
                        if not i.filename.endswith('/'):
                            out.append((rel + '!' + i.filename, i.file_size))
            else:
                out.append((rel, os.path.getsize(full)))
    return out


SKIP = re.compile(r'(\.(so|dll|dylib|exe|log)$|^vm/|^profiles/|^screenshots/|^demos/|^logs/)', re.I)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--base', default=os.path.join(ROOT, 'baseq3r'))
    ap.add_argument('--audit', help='origin audit JSON (list of {path, origin})')
    ap.add_argument('--out', default=os.path.join(ROOT, 'docs', 'assets'))
    a = ap.parse_args()

    files = [(p, s) for p, s in walk(a.base) if not SKIP.search(p)]
    lower = [p.lower() for p, _ in files]
    maps = map_names(lower)
    gen = generated_set(os.path.abspath(os.path.join(a.base, '..')))
    audit = {}
    if a.audit:
        data = json.load(open(a.audit))
        for f in (data['now'] if isinstance(data, dict) else data):
            audit[f['path'].lower()] = f['origin']

    # maps written by tools/maptools (the .map says so in its first lines)
    gen_maps = set()
    for m in maps:
        src = os.path.join(a.base, 'maps', m + '.map')
        if os.path.exists(src):
            head = open(src, errors='ignore').read(600)
            if re.search(r'(Generated|written) by tools/', head, re.I) or 'generated by tools' in head.lower():
                gen_maps.add(m)

    rows = []
    for p, size in files:
        lp = p.lower()
        bare = lp.split('!', 1)[-1]
        unit, area = unit_of(lp, maps)
        g = gen.get(bare) or next((src for rx, src in GEN_RULES if re.search(rx, bare)), '')
        if not g and unit.startswith('Karte ') and unit[6:] in gen_maps:
            g = 'tools/maptools'
        origin = audit.get(bare, '')
        stated = next((why for pfx, why in OWN_STATED if bare.startswith(pfx)), '')
        if g:
            klass = 'eigen (generiert)'
        elif stated:
            klass = 'eigen (laut Projekt)'
        elif origin in ('A', 'B'):
            klass = 'OpenArena'
        elif origin in ('C', 'D'):
            klass = 'Quake 3 (Verdacht)'
        elif origin == 'E':
            klass = 'eigen (alter Name)'
        else:
            klass = 'unbekannt'
        rows.append({'pfad': p, 'bytes': size, 'einheit': unit, 'bereich': area, 'herkunft': klass, 'generator': g, 'audit': origin})

    # coarser units: what is settled goes into one row per area, related sets share a row
    fine = collections.defaultdict(collections.Counter)
    for r in rows:
        fine[r['einheit']][r['herkunft']] += 1

    def collapse(unit, area):
        k = fine[unit]
        n = sum(k.values())
        if unit in KB or area in ('Autos', 'Karten', 'Himmel', 'Musik'):
            return unit
        if k['OpenArena'] == n:
            return f'OpenArena-Dateien ({area})'
        if k['eigen (generiert)'] == n:
            return f'Eigene generierte Dateien ({area})'
        rules = [(r'^Texturen q3r_', 'Texturen q3r_* (Projekt-Sets)'), (r'^Texturen evil', 'Texturen evil* (Evillair)'),
                 (r'^Texturen jim', 'Texturen jim*'), (r'^Modelle powerups', 'Modelle powerups'),
                 (r'^Modelle weapons2', 'Modelle weapons2 (Waffen)'), (r'^Modelle weaphits', 'Modelle weaphits'),
                 (r'^gfx', 'Oberfläche gfx'), (r'^menu', 'Oberfläche menu'), (r'^Sounds weapons', 'Sounds weapons'),
                 (r'^Sounds world', 'Sounds world'), (r'^Sounds movers', 'Sounds movers'), (r'^Sounds rally', 'Sounds rally'),
                 (r'^Sounds (aliens|metal|plastic|breakable)$', 'Sounds Effekte (aliens, metal, plastic, breakable)'),
                 (r'^Modelle (test|mapobjects)$', 'Modelle Sonstiges (test, mapobjects ohne Unterordner)')]
        for rx, new in rules:
            if re.search(rx, unit):
                return new
        return unit

    for r in rows:
        r['einheit'] = collapse(r['einheit'], r['bereich'])

    units = collections.OrderedDict()
    for r in sorted(rows, key=lambda r: (r['bereich'], r['einheit'])):
        u = units.setdefault(r['einheit'], {'bereich': r['bereich'], 'n': 0, 'bytes': 0, 'k': collections.Counter(), 'gen': set(), 'pk3': set()})
        u['n'] += 1
        u['bytes'] += r['bytes']
        u['k'][r['herkunft']] += 1
        if r['generator']:
            u['gen'].add(r['generator'])
        if '!' in r['pfad']:
            u['pk3'].add(r['pfad'].split('!')[0])

    out_units = []
    for name, u in units.items():
        k = u['k']
        mix = ', '.join(f'{v} {n}' for n, v in k.most_common())
        if name in KB:
            status, herkunft, lizenz, todo = KB[name]
        elif k['eigen (generiert)'] == u['n']:
            status, herkunft, lizenz, todo = OWN_GEN, 'erzeugt von ' + ', '.join(sorted(u['gen'])), GAME, DONE
        elif name.startswith('Karte ') and 'test' in name:
            status, herkunft, lizenz, todo = OWN, 'Test- oder Werkstattkarte, für Q3Rally erstellt', GAME, DONE + '; kann aus dem Release raus'
        elif k['eigen (generiert)'] + k['OpenArena'] == u['n']:
            status, herkunft, lizenz, todo = OWN_GEN, 'erzeugt von ' + ', '.join(sorted(u['gen'])) + ' und OpenArena', 'GPLv2', CREDIT
        elif u['bereich'] == 'Text/Code':
            status, herkunft, lizenz, todo = OWN, 'Skripte, Shader, Konfiguration und Bot-Daten des Projekts', GAME, DONE
        elif k['OpenArena'] == u['n']:
            status, herkunft, lizenz, todo = FREE, 'OpenArena', 'GPL', CREDIT
        else:
            hint = next((v for pfx, v in PACK_HINT.items() if name.startswith('Texturen ' + pfx)), '')
            if hint:
                status, herkunft, lizenz, todo = REL, hint + '; laut Projekt freigegeben', GAME, CREDIT
            elif k['eigen (alter Name)'] + k['eigen (generiert)'] + k['eigen (laut Projekt)'] + k['OpenArena'] == u['n']:
                status, herkunft, lizenz, todo = OWN, 'eigen und/oder OpenArena', GAME, DONE
            else:
                # the project states that everything without a named third party was made for Q3Rally
                status, herkunft, lizenz, todo = OWN, 'für Q3Rally erstellt (laut Projekt)', GAME, DONE
        if k['Quake 3 (Verdacht)']:
            todo = f"{k['Quake 3 (Verdacht)']} Datei(en) mit Quake-3-Verdacht prüfen. " + todo
        if k['OpenArena'] and status not in (FREE,) and 'OpenArena' not in todo:
            todo += f"; enthält {k['OpenArena']} OpenArena-Datei(en) (GPL, in den Credits genannt)"
        ask = HINTS.get(u['bereich'], '') if status in (UNKNOWN, ASK, CHECK, BAD) else ''
        out_units.append({'Bereich': u['bereich'], 'Einheit': name, 'Dateien': u['n'], 'MB': round(u['bytes'] / 1e6, 2),
                          'Zusammensetzung': mix, 'Herkunft laut Repo': herkunft, 'Lizenz bisher': lizenz,
                          'Status': status, 'Was zu tun ist': todo, 'Wen fragen (Readme)': ask,
                          'In pk3': ', '.join(sorted(u['pk3']))})

    os.makedirs(a.out, exist_ok=True)
    with open(os.path.join(a.out, 'lizenz_einheiten.csv'), 'w', newline='', encoding='utf-8') as f:
        w = csv.DictWriter(f, fieldnames=list(out_units[0]))
        w.writeheader()
        w.writerows(out_units)
    with open(os.path.join(a.out, 'lizenz_dateien.csv'), 'w', newline='', encoding='utf-8') as f:
        w = csv.DictWriter(f, fieldnames=['pfad', 'bytes', 'einheit', 'bereich', 'herkunft', 'generator', 'audit'])
        w.writeheader()
        w.writerows(sorted(rows, key=lambda r: r['pfad'].lower()))
    c = collections.Counter(u['Status'] for u in out_units)
    print(len(rows), 'Dateien in', len(out_units), 'Einheiten')
    for s, n in c.most_common():
        print(f'  {s:22s} {n:4d} Einheiten, {sum(u["Dateien"] for u in out_units if u["Status"] == s):5d} Dateien')


if __name__ == '__main__':
    main()
