"""License inventory of the game data (baseq3r/).

    python3 tools/assets/license_inventory.py [--base baseq3r] [--audit herkunft.json] [--out docs/assets]

Every file (also inside .pk3) is put into a unit - a car, a map, a texture
set, a sound group, a music track - and each unit gets what is known about
where it comes from and under which license it may be shipped. The result
is two CSV files:

    lizenz_einheiten.csv   one row per unit: files, size, origin, license, status, what to do
    lizenz_dateien.csv     one row per file: unit, origin class, generated by

What is known comes from three places:
  1. the generators in tools/ (their output is Q3Rally's own and its source is in the repo),
  2. the knowledge base below (CREDITS / readme files, map titles, team statements),
  3. optionally the origin audit (--audit): OpenArena (A identical, B edited),
     Quake 3 (C likely, D suspect), Q3Rally's own under an old name (E), unknown (F, G).

The knowledge base is the part to keep up to date: when a license has been
cleared, change the unit's entry here and run the script again.
"""
